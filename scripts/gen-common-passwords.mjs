#!/usr/bin/env node
// Regenerates server/src/auth/common-passwords.ts from a public common-password list.
//
//   node scripts/gen-common-passwords.mjs [path-or-url]
//
// Default source: Probable-Wordlists "Top1575-probable-v2", which is ranked by real-world
// frequency rather than by dictionary order, so the top entries are the passwords people
// actually choose. Re-run this if the policy ever needs a longer list.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_SOURCE =
  "https://raw.githubusercontent.com/berzerk0/Probable-Wordlists/master/Real-Passwords/Top1575-probable-v2.txt";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "server/src/auth/common-passwords.ts");
const source = process.argv[2] ?? DEFAULT_SOURCE;

const text = /^https?:\/\//.test(source)
  ? await fetch(source).then((r) => {
      if (!r.ok) throw new Error(`${r.status} fetching ${source}`);
      return r.text();
    })
  : await fs.readFile(source, "utf8");

const set = new Set();
let skipped = 0;
for (const line of text.split(/\r?\n/)) {
  const password = line.trim().toLowerCase();
  if (!password) continue;
  // These three sequences would break out of the template literal the list is stored in. Every
  // such entry is shorter than the 10-character minimum, so the length rule already rejects them.
  if (password.includes("`") || password.includes("\\") || password.includes("${")) {
    skipped += 1;
    continue;
  }
  set.add(password);
}

const list = [...set].sort();

const file = `/**
 * The most common real-world passwords, rejected by the password policy in brief §6.
 *
 * Generated by scripts/gen-common-passwords.mjs from
 * ${source}
 * (deduplicated, lowercased${skipped ? `, ${skipped} entr${skipped === 1 ? "y" : "ies"} dropped for containing a backtick or backslash` : ""}).
 * Do not edit by hand.
 *
 * Stored as one newline-delimited string rather than ${list.length} quoted array entries: far
 * fewer bytes, and it parses in a single split.
 */
const RAW = \`
${list.join("\n")}
\`;

export const COMMON_PASSWORDS: ReadonlySet<string> = new Set(RAW.trim().split("\\n"));
`;

await fs.mkdir(path.dirname(outFile), { recursive: true });
await fs.writeFile(outFile, file);
console.log(`wrote ${list.length} passwords to ${path.relative(root, outFile)}${skipped ? ` (${skipped} skipped)` : ""}`);
