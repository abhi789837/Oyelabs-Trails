#!/usr/bin/env node
// Generates src/content/manifest.generated.ts: the always-loaded table of contents
// (tracks, modules, topic metadata). Runs automatically before `dev` and `build`.
import fs from "node:fs";
import path from "node:path";
import { CONTENT_DIR, loadCurriculum } from "./load.mjs";

const { registry, loaded } = await loadCurriculum();
const byId = new Map(loaded.map((l) => [l.entry.id, l.mod]));

const manifest = registry.map((track) => ({
  id: track.id,
  name: track.name,
  tagline: track.tagline,
  accentToken: track.accentToken,
  modules: track.modules.map((entry) => {
    const mod = byId.get(entry.id);
    if (!mod) {
      return { id: entry.id, trackId: track.id, name: entry.name, description: "", topics: [], available: false };
    }
    return {
      id: mod.id,
      trackId: track.id,
      name: mod.name,
      description: mod.description,
      ...(mod.refs?.length ? { refs: mod.refs } : {}),
      available: true,
      topics: mod.topics.map((t) => ({
        id: t.id,
        moduleId: mod.id,
        trackId: track.id,
        title: t.title,
        level: t.level,
        estMinutes: t.estMinutes,
        ...(t.isMilestone ? { isMilestone: true } : {}),
        challengeType: t.challengeType,
        challengeSize: t.challengeType === "quiz" ? (t.quiz?.length ?? 0) : (t.codeChallenge?.testCases.length ?? 0),
      })),
    };
  }),
}));

const out = `// AUTO-GENERATED by scripts/content/build-manifest.mjs. Do not edit by hand.
// Regenerate with \`npm run content:manifest\` (runs automatically before dev and build).
import type { TrackMeta } from "./manifest-types";

export const manifest: TrackMeta[] = ${JSON.stringify(manifest, null, 2)};
`;

const target = path.join(CONTENT_DIR, "manifest.generated.ts");
const previous = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
if (previous !== out) fs.writeFileSync(target, out);
const topics = manifest.reduce((n, t) => n + t.modules.reduce((m, mod) => m + mod.topics.length, 0), 0);
console.log(`manifest: ${loaded.length} modules available, ${topics} topics${previous === out ? " (unchanged)" : ""}`);
